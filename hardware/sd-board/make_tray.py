"""The printed tray the SD board slides into (the user, 2026-10-25): it sits on the FM-1 board's back, under the board,
round the back cover's pole by the battery's plug. A 0.8 mm floor under the whole board (it keeps its copper off the
FM-1's), a rail along each side with a groove the board's edge slides in (held up and down), and a collar round the
pole that stops the board. Outside the case: slide the board in from the bottom end until it meets the collar, then
set the tray on the pole; the bottom wall keeps it from sliding back. All solid, one piece (no void).
Writes sd-tray.scad and, with OpenSCAD, sd-tray.stl, in the FM-1 board's millimetres (u from its left edge, v up from
its bottom edge, seen from the back; MEASUREMENTS.md):

  /Applications/KiCad/KiCad.app/Contents/Frameworks/Python.framework/Versions/3.9/bin/python3.9 make_tray.py
"""
import os
import subprocess

import pcbnew

HERE = os.path.dirname(os.path.abspath(__file__))
FLOOR, PCB, PLAY, LIP = 0.8, 1.6, 0.25, 0.7      # (mm: the floor, the board, its play in the groove, the lip over it)
SIDE, OVER = 0.3, 0.8                            # (the groove reaches 0.3 past the board's edge; the lip covers 0.8)
LEFT, RIGHT = 72.6 + 0.6, 72.6 + 30.0 - 0.6      # the rails' outsides: 0.6 mm clear of the battery and the plug
POLE, POLE_D, COLLAR_H = (78.0, 40.0), 6.9, 5.6  # the pole (l, m, i) and the collar's height (the pole stands 6 mm)
POST_H = 4.3                                     # two posts on the rails' bottom ends, up toward the cover (its edge
                                                 # band is a couple of mm lower, t: about 4.8 mm left, taken)
# Only the collar and the posts reach toward the cover: the battery's cable crosses over the board and the tray (the
# user, 2026-10-25), in a band about 8 mm wide some 10 mm below the speaker plug (w2: 44 mm up), about 30 to 38 mm up.
COLLAR_IN = (POLE_D + 0.4) / 2
COLLAR_OUT = COLLAR_IN + 1.0

board = pcbnew.LoadBoard(os.path.join(HERE, "sd-board.kicad_pcb"))
outline = pcbnew.SHAPE_POLY_SET()
board.GetBoardPolygonOutlines(outline, False)
ring = outline.Outline(0)
pts = [(round(pcbnew.ToMM(ring.CPoint(i).x) - 100.0, 3), round(200.0 - pcbnew.ToMM(ring.CPoint(i).y), 3))
       for i in range(ring.PointCount())]
u0 = min(u for u, _ in pts)                      # the board's left and right edges, bottom, and where its left edge
u1 = max(u for u, _ in pts)                      # ends under the seat
v0 = min(v for _, v in pts)
v1 = max(v for _, v in pts)
v_left = max(v for u, v in pts if abs(u - u0) < 0.01)

top = FLOOR + PCB + PLAY + LIP
groove = FLOOR + PCB + PLAY


def box(a, b, c, d, z0, z1):
    return f"translate([{a:.3f}, {b:.3f}, {z0:.3f}]) cube([{c - a:.3f}, {d - b:.3f}, {z1 - z0:.3f}]);"


scad = os.path.join(HERE, "sd-tray.scad")
with open(scad, "w") as f:
    f.write("// generated by make_tray.py: the SD board's tray (u, v in mm from the FM-1 board's left and bottom edges)\n")
    f.write("$fn = 96;\nunion() {\n")
    f.write(f"  linear_extrude({FLOOR}) union() {{ offset(delta={SIDE}) polygon({[list(p) for p in pts]});\n")
    f.write(f"    translate([{POLE[0]}, {POLE[1]}]) circle(r={COLLAR_OUT}); }}\n")
    f.write(f"  {box(LEFT, v0 - SIDE, u0 - SIDE, v_left, 0, top)}   // the left rail\n")
    f.write(f"  {box(LEFT, v0 - SIDE, u0 + OVER, v_left, groove, top)}   // its lip\n")
    f.write(f"  {box(u1 + SIDE, v0 - SIDE, RIGHT, v1, 0, top)}   // the right rail\n")
    f.write(f"  {box(u1 - OVER, v0 - SIDE, RIGHT, v1, groove, top)}   // its lip\n")
    f.write(f"  {box(LEFT, v0 - SIDE, u0 + OVER, v0 + 1.2, groove, POST_H)}   // a post on the lip (the groove free)\n")
    f.write(f"  {box(u1 - OVER, v0 - SIDE, RIGHT, v0 + 1.2, groove, POST_H)}   // a post on the lip\n")
    f.write(f"  {box(u1 - OVER, v1 - 1.5, RIGHT, v1, groove, COLLAR_H)}   // a post at the right rail's top end\n")
    f.write(f"  translate([{POLE[0]}, {POLE[1]}, 0]) difference() {{ cylinder(r={COLLAR_OUT}, h={COLLAR_H});"
            f" translate([0, 0, -1]) cylinder(r={COLLAR_IN}, h={COLLAR_H + 2}); }}   // the collar\n")
    f.write("}\n")
f.close()
# (the collar's hole goes through the floor too: the pole stands on the FM-1 board)
src = open(scad).read().replace("$fn = 96;\nunion() {", "$fn = 96;\ndifference() { union() {", 1)
src = src.rstrip().rstrip("}") + f"}}\n  translate([{POLE[0]}, {POLE[1]}, -1]) cylinder(r={COLLAR_IN}, h={COLLAR_H + 2});\n}}\n"
open(scad, "w").write(src)
stl = os.path.join(HERE, "sd-tray.stl")
subprocess.run(["openscad", "-o", stl, scad], check=True, capture_output=True)
print("wrote", scad, stl, f"(board {u0}..{u1} x {v0}..{v1}; rails to {top} mm, collar {COLLAR_H} mm)")
