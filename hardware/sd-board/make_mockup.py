"""A mockup to 3D-print, to try the board in the FM-1: the board's outline 1.6 mm thick and each part as a solid block
(its courtyard, its height) standing on it, all one piece (the parts' own 3D models float above the board in a slicer).
Writes mockup-printable.scad and, with OpenSCAD, mockup-printable.stl; with "card-out", a released microSD card in it
too, CARD_OUT mm out through the wall's slot (an estimate: the socket's travel is not measured). ("card-in" also
works, but a latched card hides inside the socket's solid block: it looks like the empty one, so it is not kept.)

  /Applications/KiCad/KiCad.app/Contents/Frameworks/Python.framework/Versions/3.9/bin/python3.9 make_mockup.py [card-out]
"""
import os
import subprocess
import sys

import pcbnew

HERE = os.path.dirname(os.path.abspath(__file__))
THICK = 1.6
CARD = sys.argv[1] if len(sys.argv) > 1 else ""
CARD_W, CARD_L, CARD_T, CARD_OUT = 11.0, 15.0, 0.8, 4.0   # (a microSD card: 11 x 15 x 0.7-1.0 mm)
HEIGHT = {"J1": 1.85, "J2": 1.0, "J3": 1.0, "U1": 1.1, "C1": 1.3, "C2": 0.8}    # (mm above the board; the resistors 0.55)

board = pcbnew.LoadBoard(os.path.join(HERE, "sd-board.kicad_pcb"))
outline = pcbnew.SHAPE_POLY_SET()
board.GetBoardPolygonOutlines(outline, False)
ring = outline.Outline(0)
pts = [(pcbnew.ToMM(ring.CPoint(i).x), -pcbnew.ToMM(ring.CPoint(i).y)) for i in range(ring.PointCount())]

blocks = []
for fp in board.GetFootprints():
    court = fp.GetCourtyard(pcbnew.F_CrtYd)
    if not court.OutlineCount():
        continue
    bb = court.BBox()
    x0, x1 = pcbnew.ToMM(bb.GetLeft()), pcbnew.ToMM(bb.GetRight())
    y0, y1 = -pcbnew.ToMM(bb.GetBottom()), -pcbnew.ToMM(bb.GetTop())
    blocks.append((fp.GetReference(), x0, y0, x1 - x0, y1 - y0, HEIGHT.get(fp.GetReference(), 0.55)))

if CARD:                                         # the card: centred on the socket, from its front (y up = inward)
    j1 = next(fp for fp in board.GetFootprints() if fp.GetReference() == "J1")
    cx, front = pcbnew.ToMM(j1.GetPosition().x), -(pcbnew.ToMM(j1.GetPosition().y) + 9.62)
    out = CARD_OUT if CARD == "card-out" else 0.0
    blocks.append(("card", cx - CARD_W / 2, front - out, CARD_W, CARD_L, 0.25 + CARD_T))
suffix = f"-{CARD}" if CARD else ""
scad = os.path.join(HERE, f"mockup-printable{suffix}.scad")
with open(scad, "w") as f:
    f.write("// generated by make_mockup.py: the SD board's outline and its parts as blocks\nunion() {\n")
    f.write(f"  linear_extrude({THICK}) polygon({[[round(x, 3), round(y, 3)] for x, y in pts]});\n")
    for ref, x, y, w, d, h in blocks:
        f.write(f"  translate([{x:.3f}, {y:.3f}, {THICK - 0.01}]) cube([{w:.3f}, {d:.3f}, {h + 0.01}]);  // {ref}\n")
    f.write("}\n")
stl = os.path.join(HERE, f"mockup-printable{suffix}.stl")
subprocess.run(["openscad", "-o", stl, scad], check=True, capture_output=True)
print("wrote", scad, stl)
