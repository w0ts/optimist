"""A mockup to 3D-print, to try the short board in the FM-1: the outline, THICK mm, and each part as a solid block (its
courtyard, its height) above the top or under the bottom, all one piece. Writes mockup-printable.scad and, with OpenSCAD,
mockup-printable.stl. The card is not added: it sits inside the socket's block when closed.

  /Applications/KiCad/KiCad.app/Contents/Frameworks/Python.framework/Versions/3.9/bin/python3.9 make_mockup.py
"""
import os
import subprocess

import pcbnew

HERE = os.path.dirname(os.path.abspath(__file__))
THICK = 1.0
HEIGHT = {"J1": 1.83, "J2": 2.0, "J3": 2.0, "U1": 1.1, "U2": 1.5, "U3": 1.5, "C1": 1.3, "C2": 0.8, "C3": 0.8, "FB1": 0.8,
          "RT1": 2.5, "RT5": 2.5, "RT6": 2.5}    # (mm off the board; the resistors 0.55; J1 from LCSC's table, not Hirose's drawing;
                                                 # the twins: a 1/4 W leaded resistor lying between the pads, its body the courtyard, 2.5 high)

board = pcbnew.LoadBoard(os.path.join(HERE, "sd-board.kicad_pcb"))
outline = pcbnew.SHAPE_POLY_SET()
board.GetBoardPolygonOutlines(outline, False)
ring = outline.Outline(0)
pts = [(pcbnew.ToMM(ring.CPoint(i).x), -pcbnew.ToMM(ring.CPoint(i).y)) for i in range(ring.PointCount())]

blocks = []
for fp in board.GetFootprints():
    bottom = fp.GetLayer() == pcbnew.B_Cu
    court = fp.GetCourtyard(pcbnew.B_CrtYd if bottom else pcbnew.F_CrtYd)
    if not court.OutlineCount() or fp.GetReference().startswith("TP"):   # (the test pad: copper only, nothing stands)
        continue
    bb = court.BBox()
    x0, x1 = pcbnew.ToMM(bb.GetLeft()), pcbnew.ToMM(bb.GetRight())
    y0, y1 = -pcbnew.ToMM(bb.GetBottom()), -pcbnew.ToMM(bb.GetTop())
    blocks.append((fp.GetReference(), x0, y0, x1 - x0, y1 - y0, HEIGHT.get(fp.GetReference(), 0.55), bottom))

scad = os.path.join(HERE, "mockup-printable.scad")
with open(scad, "w") as f:
    f.write("// generated by make_mockup.py: the short SD board's outline and its parts as blocks\nunion() {\n")
    f.write(f"  linear_extrude({THICK}) polygon({[[round(x, 3), round(y, 3)] for x, y in pts]});\n")
    for ref, x, y, w, d, h, bottom in blocks:
        z = -h if bottom else THICK - 0.01
        f.write(f"  translate([{x:.3f}, {y:.3f}, {z:.3f}]) cube([{w:.3f}, {d:.3f}, {h + 0.01}]);  // {ref}\n")
    f.write("}\n")
stl = os.path.join(HERE, "mockup-printable.stl")
subprocess.run(["openscad", "-o", stl, scad], check=True, capture_output=True)
print("wrote", scad, stl)
