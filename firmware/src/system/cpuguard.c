/* The predictive CPU guard (FELUCCA_CPU_GUARD, builder item CPU_GUARD; docs/CPU-GUARD.md). After Flowstate's
 * guard (firmware/src/guard.c, docs/guardrails.md 2.5) by Zakaria Chowdhury, GPL-3.0-only: its CPU part, a load
 * that is the larger of the measured one and an estimate from what sounds, held over a ceiling for 8 halves.
 *
 * Every DMA half (audio.c, the audio interrupt):
 *   cg_pre()     before the render: the prediction, the last half as measured plus what the cost model says
 *                changed since (voices started or ended; cpuguard_costs.h: target instructions a sample per
 *                engine voice, the idle mix, the drums, each X0X channel, a part's COMP insert while it runs, the drum
 *                bus's DIST and COMP;
 *                generated by tools/builder/cpu_costs.py from tests/cpu_baseline.txt and the emulator's scale,
 *                fitted so the model stays at or under the
 *                measured load). What the guard eased shows in the measurement at once. After a half over the
 *                ceiling, a half predicted to run late steps up before it renders; from NOTES on, the voices whose
 *                predicted cost brings it under the ceiling fade out at once (CG_SHED_MAX at most; none left: the reverb). Else a shed
 *                cg_post asked for.
 *   cg_post(us)  after it: the measured load (its time in the interrupt); the load is the larger of the two.
 *                Over the ceiling (85 %) for CG_HOLD halves in a row, or one half that ran late (100 %): one
 *                level up (cpuguard.h: quality, UNISON, notes, the reverb; a level with nothing to ease in what sounds
 *                now is passed). From NOTES on, a half over the ceiling sheds a voice before the next (as audio.c
 *                did on its own), never from the bass or the lead, never a drum. The drums ease at quality: their
 *                tails end sooner (a synthesised voice under -40 dBFS, an X0X 808 voice 40 dB under its peak).
 *                Release: one level down after CG_RELEASE halves (2 s) under the release level (80 %), counting
 *                the load the level saves (measured over the CG_HOLD halves after its step): a level comes off
 *                only when the music it held back would fit again, so it does not come and go every 2 s.
 * Nothing else changes: below the ceiling the guard does nothing, and the host (no timer) never steps. */
#include "cpuguard_costs.h"
#if FELUCCA_INS_JCHORUS
#define CG_COST_JUNO 140u   /* JUNO CHORUS while it runs, an instance: ~130 host instructions a sample (tests/juno_cho_test.c)
                             * x 1.04, not yet a cpu_costs.py entry */
#endif
#if CG_REV
#define REV_LIVE() ((int)rev_live)
#else
#define REV_LIVE() 0
#endif

#define CG_CEIL 218u                     /* 85 % of a half, 1/256 */
#define CG_REL (CG_CEIL - CG_CEIL / 16u) /* 80 %: the release level (Flowstate: 1/16 under the ceiling) */
#define CG_FULL 256u                     /* a whole half: late */
#define CG_HOLD 8u                       /* halves over the ceiling before a step (46 ms) */
#define CG_RELEASE 345u                  /* halves under the release level before a level comes off (2 s) */
#define CG_HALF_US (HALF_FRAMES * 1000000u / FS)   /* a half's time, us */
#define CG_FAR __attribute__((noinline))   /* (once a half, from the audio ISR: in XIP, called FAR) */
#define CG_SHED_MAX 4u                   /* voices a half predicted late fades out at most */
/* the reactive path ("Spikes"): late halves scattered among lighter ones. Each late half adds CG_SPK_HIT to a leaky count
 * that loses 1 a half; at CG_SPK_ON (3 late halves within ~30 halves, or a steady 3 a second and more) it reacts: one
 * level up, from NOTES on a voice cut (none left: the reverb) and the voices capped one under what sounded (a new note then steals the oldest).
 * One late half (a flash write, a USB burst) never reacts, nor do late halves at a light load (under CG_RFLOOR: the
 * music is not what makes them late). A level a reaction set comes off only under the load the drop-outs came at less
 * CG_RMARGIN (rcap); the cap rises a voice after CG_VSTEP halves with no late one */
#define CG_SPK_HIT 64u
#define CG_SPK_ON 160u
#define CG_RFLOOR 128u                   /* 50 % of a half: the measured mean (avg) the reactive path needs */
#define CG_RMARGIN 16u                   /* 1/16 of a half */
#ifndef CG_VSTEP
#define CG_VSTEP 345u                    /* halves (2 s) with no late one before the cap rises a voice */
#endif
/* a late half holds a level's release back only where the reactive path counts it: at a
 * mean of CG_RFLOOR or more. Under it a late half is not the music's (USB, Bluetooth, a flash write) and steps nothing,
 * so it holds nothing up either (2026-10-29, the user: "the FDN8 reverb stops working randomly": before, one late half
 * every second or two at any load kept a reaction's REVERB level, the reverb off, for good: tests/cpuguard_test.c 11) */
#define CG_LATE_HOLDS(late) ((late) && cg.avg >= CG_RFLOOR)
#define CG_VMIN 2u                       /* the cap's floor */

/* a part the guard never sheds: MONO / LEGATO / UNISON (the bass and the lead), and a monophonic engine */
static int cg_keep(const track_t *t)
{
    return t->p[P_VOICE] != V_POLY || trk_nvoice(t) == 1u;
}

static uint32_t cg_vcost(const track_t *t)   /* a voice of this part: target instructions a sample */
{
    uint32_t u = eng_uid(t->engine);
    return CG_VCOST[u < CG_NVCOST ? u : 0u];
}

#define INS_SNDI (INS_CHO || INS_REV || INS_DLY)
#if INS_SNDI
/* the CHO DLY REV inserts (fxi_send.c, 2026-10-29): a copy's cost, 0 not built */
static uint32_t cg_sndi_c(uint32_t t)
{
#if INS_CHO
    if (t == FXT_CHO)
        return CG_COST_CHOI;
#endif
#if INS_REV
    if (t == FXT_REV)
        return CG_COST_REVI;
#endif
#if INS_DLY
    if (t == FXT_DLY)
        return CG_COST_DLYI;
#endif
    (void)t;
    return 0;
}
/* a CHO DLY REV insert's wet share now on the audio's index i (limited types: their instance's) */
static __attribute__((noinline)) int32_t cg_sndi_w(uint32_t t, uint32_t i)
{
    uint32_t n = ifx_lim_at(t, i);
    if (n == FXI_NONE)
        return 0;
#if INS_CHO
    if (t == FXT_CHO)
        return ifx_choi[n % FXI_TN0].w;
#endif
#if INS_REV
    if (t == FXT_REV)
        return ifx_room[n % FXI_TN5].w;
#endif
#if INS_DLY
    if (t == FXT_DLY)
        return ifx_tdly[n % FXI_TN6].w;
#endif
    return 0;
}
/* track k's (the audio's index i: a part's, the drum bus's) CHO DLY REV inserts that run now: set (in a slot, FX on, its
 * amount: the track's P_CHOR P_REV P_DLY, the insert's MIX, with an instance) or fading */
static __attribute__((noinline)) uint32_t cg_sndi(uint32_t k, uint32_t i, int32_t on)
{
    uint32_t n = 0;
#if INS_CHO
    if ((on && INS_ON(k, FXT_CHO) && trk[k].p[P_CHOR] && ifx_has(FXT_CHO, k)) || cg_sndi_w(FXT_CHO, i))
        n += CG_COST_CHOI;
#endif
#if INS_REV
    if ((on && INS_ON(k, FXT_REV) && trk[k].p[P_REV] && ifx_has(FXT_REV, k)) || cg_sndi_w(FXT_REV, i))
        n += CG_COST_REVI;
#endif
#if INS_DLY
    if ((on && INS_ON(k, FXT_DLY) && trk[k].p[P_DLY] && ifx_has(FXT_DLY, k)) || cg_sndi_w(FXT_DLY, i))
        n += CG_COST_DLYI;
#endif
    return n;
}
#endif
/* the insert slots (fx_slots.c ins_slot, fx.c ins_part, dbus_run; D9: every slot modelled, none ever switched off):
 * part p's that run now (a sounding part): DIST while its amount is set (in a slot, FX on), the FILTER while it is
 * not at rest (set, or gliding open: fx.c tflt_block), COMP while set or letting go. The QUALITY level runs the drum
 * bus's on L / R only, 2 of its 5 channels: their cost x 2 / 5 */
static uint32_t cg_ins_part(uint32_t p)
{
    uint32_t n = 0, on = (uint32_t)fx_on(&trk[p]);
    (void)on;
#if FELUCCA_FX_DIST
    n += on && INS_ON(p, FXT_DIST) && trk[p].p[P_DIST] ? CG_COST_PDIST : 0u;
#endif
#if TFLT_ON
    n += tflt[p].mode ? CG_COST_PFILT : 0u;
#endif
#if FELUCCA_MASTER_COMP
    if ((on && INS_ON(p, FXT_COMP) && trk[p].p[P_TCOMP]) || tcomp[p].gr16 || tcomp[p].g13 != 8192)
        n += CG_COST_TCOMP;                           /* (fx.c tcomp_run: on, or letting go) */
    n += tlim[p].on ? CG_COST_TLIM : 0u;              /* (its CEIL) */
#endif
#if FELUCCA_FX_DUST
    n += on && INS_ON(p, FXT_DUST) && trk[p].p[P_TDUST] ? CG_COST_PDUST : 0u;
#endif
#if INS_FX
    {   /* the further inserts (insfx.c): set in a slot, or fading out */
        uint32_t t;
        for (t = 0; t < FXT_N; t++)
            if (IFX_FUR(t) && FXT_AMT[t] != 0xFFu && ((on && INS_ON(p, t) && trk[p].p[FXT_AMT[t]] && ifx_has(t, p)) || ifx_wn(t, p)))
                n += CG_COST_PINS[IFX_FIX(t)];
    }
#endif
#if FELUCCA_INS_JCHORUS
    if ((on && INS_ON(p, FXT_JUNO) && trk[p].p[P_TJCHO] && ifx_has(FXT_JUNO, p)) || ifx_w(FXT_JUNO, p))
        n += CG_COST_JUNO;
#endif
    if (ifx_w(FXT_EQ3, p) || (on && INS_ON(p, FXT_EQ3) && trk[p].p[P_TEQ] && !eq3_flat(EQ3_V(p))))
        n += CG_COST_EQ3M;                            /* (engaged only: flat is bypassed, eq3.c) */
#if FELUCCA_INS_XDLY
    if ((on && INS_ON(p, FXT_XDLY) && trk[p].p[P_TXDLY] && ifx_has(FXT_XDLY, p)) || ifx_w(FXT_XDLY, p))
        n += CG_COST_XDLY;                            /* (set, fading or ringing on: xdly.c) */
#endif
#if INS_SNDI
    n += cg_sndi(p, p, on);                           /* (the CHO REV DLY inserts: fxi_send.c) */
#endif
    return n;
}
static uint32_t cg_bus_w(void)                        /* the drum bus's DIST and FILTER on all 5 channels */
{
    uint32_t w = 0;
#if FELUCCA_FX_DIST
    w += dbus_live ? CG_COST_DBDIST : 0u;             /* (fx.c dbus_dist_run: a signal on it) */
#endif
#if TFLT_ON
    w += tflt[TRK_DRUM].mode ? CG_COST_DBFILT : 0u;
#endif
    return w;
}
static uint32_t cg_ins_bus(void)
{
    uint32_t w = cg_bus_w(), n = CG_LEVEL >= CG_L_QUALITY ? w * 2u / 5u : w;
#if FELUCCA_MASTER_COMP
    if ((fx_on(TDRUM) && INS_ON(TRK_DRUM, FXT_COMP) && TDRUM->p[P_TCOMP]) || !tcomp_rest(&dbus_comp))
        n += CG_COST_DBCOMP;                          /* (fx.c dbus_comp_run: on, or letting go) */
    n += tlim[TRK_DRUM].on ? CG_COST_TLIM * 2u : 0u;  /* (its CEIL, L and R) */
#endif
#if FELUCCA_FX_DUST
    n += fx_on(TDRUM) && INS_ON(TRK_DRUM, FXT_DUST) && TDRUM->p[P_TDUST] ? CG_COST_DBDUST : 0u;
#endif
#if INS_FX
    {   /* the further inserts (insfx.c ifx_bus: L and R at every level) */
        uint32_t t;
        for (t = 0; t < FXT_N; t++)
            if (IFX_FUR(t) && FXT_AMT[t] != 0xFFu && ((fx_on(TDRUM) && INS_ON(TRK_DRUM, t) && TDRUM->p[FXT_AMT[t]] && ifx_has(t, TRK_DRUM)) || ifx_wn(t, IFX_BUS)))
                n += CG_COST_DBINS[IFX_FIX(t)];
    }
#endif
#if FELUCCA_INS_JCHORUS
    if ((fx_on(TDRUM) && INS_ON(TRK_DRUM, FXT_JUNO) && TDRUM->p[P_TJCHO] && ifx_has(FXT_JUNO, TRK_DRUM)) || ifx_w(FXT_JUNO, IFX_BUS))
        n += CG_COST_JUNO;                            /* (its one stereo instance) */
#endif
    if (ifx_w(FXT_EQ3, IFX_BUS) || (fx_on(TDRUM) && INS_ON(TRK_DRUM, FXT_EQ3) && TDRUM->p[P_TEQ] && !eq3_flat(EQ3_V(TRK_DRUM))))
        n += CG_COST_EQ3S;
#if FELUCCA_INS_XDLY
    if ((fx_on(TDRUM) && INS_ON(TRK_DRUM, FXT_XDLY) && TDRUM->p[P_TXDLY] && ifx_has(FXT_XDLY, TRK_DRUM)) || ifx_w(FXT_XDLY, TRK_DRUM))
        n += CG_COST_XDLY;                            /* (its one instance on the bus's mid) */
#endif
#if INS_SNDI
    n += cg_sndi(TRK_DRUM, TRK_DRUM, fx_on(TDRUM));   /* (one stereo instance each, on the bus's mid) */
#endif
    return n;
}

