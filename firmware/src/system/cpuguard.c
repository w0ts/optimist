/* the master's insert slots that run (fx.c mst_run, fx-rework): their costs on the drum bus, the same kernels on a
 * stereo pair (DIST and FILTER: the bus's 5 channels' 2 / 5; DYN's compressor: CG_COST_DBCOMP; its limiter was in the
 * idle mix before, CG_COST_BASE). In no slot or at 0: nothing */
static uint32_t cg_ins_mst(void)
{
    uint32_t n = 0, t;
    for (t = 0; t < FXT_N; t++) {
        if (!MST_ON(t))
            continue;
        if (t == FXT_DIST && mst_amt[FXT_DIST])
            n += CG_COST_DBDIST * 2u / 5u;
#if TFLT_ON
        if (t == FXT_FILT && tflt[NTRK].mode)
            n += CG_COST_DBFILT * 2u / 5u;
#endif
#if FELUCCA_MASTER_COMP
        if (t == FXT_DYN && song.g[G_CTHR])
            n += CG_COST_DBCOMP;
#endif
        if (t == FXT_DUST && FELUCCA_FX_DUST && song.g[G_DUST])
            n += CG_COST_DBDUST;
        if (IFX_FUR(t) && mst_amt[t])
            n += CG_COST_DBINS[IFX_FIX(t)];
#if FELUCCA_INS_JCHORUS
        if (t == FXT_JUNO && (mst_amt[FXT_JUNO] || ifx_w(FXT_JUNO, IFX_MST)))
            n += CG_COST_JUNO;
#endif
        if (t == FXT_EQ3 && (ifx_w(FXT_EQ3, IFX_MST) || (mst_amt[FXT_EQ3] && !eq3_flat(EQ3_V(NTRK)))))
            n += CG_COST_EQ3S;
#if FELUCCA_INS_XDLY
        if (t == FXT_XDLY && (mst_amt[FXT_XDLY] || ifx_w(FXT_XDLY, IFX_MST)))
            n += CG_COST_XDLY;
#endif
#if INS_SNDI
        if (FXT_SENDS >> t & 1u && (mst_amt[t] || cg_sndi_w(t, IFX_MST)))
            n += cg_sndi_c(t);
#endif
    }
    return n;
}
/* the returns holding another type (fx.c rt_run, fx-pool 2026-10-15): the master's costs of the same kernels on a stereo pair,
 * while set or letting go (its tail) */
static uint32_t cg_ins_rt(void)
{
    uint32_t n = 0, j, t;
    for (j = 0; j < 3u; j++) {
        int32_t a;
        t = fxs_rty[j];
        if (t == FXT_NONE)
            continue;
        a = rt_amt(j);
        if (t == FXT_DIST && a)
            n += CG_COST_DBDIST * 2u / 5u;
#if TFLT_ON
        if (t == FXT_FILT && rt_sto[j].f.mode)
            n += CG_COST_DBFILT * 2u / 5u;
#endif
#if FELUCCA_MASTER_COMP
        if (t == FXT_DYN && a)
            n += CG_COST_DBCOMP;
#endif
        if (t == FXT_DUST && FELUCCA_FX_DUST && a)
            n += CG_COST_DBDUST;
#if INS_FX
        if (IFX_FUR(t) && (a || ifx_wn(t, IFX_RT(j))))
            n += CG_COST_DBINS[IFX_FIX(t)];
#endif
#if FELUCCA_INS_JCHORUS
        if (t == FXT_JUNO && (a || ifx_w(FXT_JUNO, IFX_RT(j))))
            n += CG_COST_JUNO;
#endif
        if (t == FXT_EQ3 && (ifx_w(FXT_EQ3, IFX_RT(j)) || (a && !eq3_flat(EQ3_V(NTRK + 2u + j)))))
            n += CG_COST_EQ3S;
    }
    return n;
}
