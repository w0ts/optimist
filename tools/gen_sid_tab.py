#!/usr/bin/env python3
# SPDX-License-Identifier: GPL-2.0-or-later
# Generates firmware/src/sid_tab.h (the data of the SID engine, eng_sid.c) from a checkout of reSID:
#   tools/gen_sid_tab.py <resid-dir> [firmware/src/sid_tab.h]
#   git clone https://github.com/simonowen/resid.git     (reSID 0.16, Dag Lem, GPL-2.0-or-later)
# The output is committed: the build does not need reSID.
#
#   SID_WAVE[model][k][4096]  the combined waveforms sampled from real chips (wave*.cc): k 0 SAW+TRI, 1 PULSE+TRI,
#                             2 PULSE+SAW, 3 PULSE+SAW+TRI; model 0 MOS6581, 1 MOS8580
#   SID_W0[model][2048]       the filter's w0 for each value of the 11-bit FC register: reSID's cubic-spline curve of
#                             the cutoff frequency (filter.cc f0_points_*), as 2 pi f 1.048576 / 2 (it does not fit 16 bits), limited to W0_CAP_HZ
#   SID_Q1024[16]             1024 / (0.707 + res / 15)
import math
import re
import sys
from pathlib import Path

W0_CAP_HZ = 12000      # reSID's own limit is 4 kHz (its steps are 8 cycles; the engine's are 4 a sample, ~5.6 cycles)

F0_6581 = [(0, 220), (0, 220), (128, 230), (256, 250), (384, 300), (512, 420), (640, 780), (768, 1600), (832, 2300),
           (896, 3200), (960, 4300), (992, 5000), (1008, 5400), (1016, 5700), (1023, 6000), (1023, 6000),
           (1024, 4600), (1024, 4600), (1032, 4800), (1056, 5300), (1088, 6000), (1120, 6600), (1152, 7200),
           (1280, 9500), (1408, 12000), (1536, 14500), (1664, 16000), (1792, 17100), (1920, 17700), (2047, 18000),
           (2047, 18000)]
F0_8580 = [(0, 0), (0, 0), (128, 800), (256, 1600), (384, 2500), (512, 3300), (640, 4100), (768, 4800), (896, 5600),
           (1024, 6500), (1152, 7500), (1280, 8400), (1408, 9200), (1536, 9800), (1664, 10500), (1792, 11000),
           (1920, 11700), (2047, 12500), (2047, 12500)]


def f0_curve(pts):
    """reSID's spline.h interpolate(): a cubic through each segment, tangents from the neighbours"""
    f = [0] * 2048
    X = lambda i: pts[i][0]
    Y = lambda i: pts[i][1]
    for i in range(len(pts) - 3):
        p0, p1, p2, p3 = i, i + 1, i + 2, i + 3
        if X(p1) == X(p2):
            continue
        if X(p0) == X(p1) and X(p2) == X(p3):
            k1 = k2 = (Y(p2) - Y(p1)) / (X(p2) - X(p1))
        elif X(p0) == X(p1):
            k2 = (Y(p3) - Y(p1)) / (X(p3) - X(p1))
            k1 = (3 * (Y(p2) - Y(p1)) / (X(p2) - X(p1)) - k2) / 2
        elif X(p2) == X(p3):
            k1 = (Y(p2) - Y(p0)) / (X(p2) - X(p0))
            k2 = (3 * (Y(p2) - Y(p1)) / (X(p2) - X(p1)) - k1) / 2
        else:
            k1 = (Y(p2) - Y(p0)) / (X(p2) - X(p0))
            k2 = (Y(p3) - Y(p1)) / (X(p3) - X(p1))
        x1, y1, x2, y2 = X(p1), Y(p1), X(p2), Y(p2)
        dx, dy = x2 - x1, y2 - y1
        a = ((k1 + k2) - 2 * dy / dx) / (dx * dx)
        b = ((k2 - k1) / dx - 3 * (x1 + x2) * a) / 2
        c = k1 - (3 * x1 * a + 2 * b) * x1
        d = y1 - ((x1 * a + b) * x1 + c) * x1
        for x in range(x1, x2 + 1):
            f[x] = max(0, int(((a * x + b) * x + c) * x + d))
    return f


def rows(vals, per):
    return ["    " + ", ".join(str(v) for v in vals[i:i + per]) + "," for i in range(0, len(vals), per)]


def main(resid, out):
    L = ["/* SPDX-License-Identifier: GPL-2.0-or-later */",
         "/* Data of reSID 0.16 (Copyright (C) 2004 Dag Lem <resid@nimrod.no>, GPL-2.0-or-later; github.com/simonowen/resid):",
         " * the combined waveforms of real MOS 6581 / 8580 chips (wave*.cc) and the filter's cutoff curves (filter.cc).",
         " * Generated by tools/gen_sid_tab.py: do not edit. */",
         "#pragma once", "#include <stdint.h>", ""]
    L.append("static const uint8_t SID_WAVE[2][4][4096] = {")
    for model in ("6581", "8580"):
        L.append("    {")
        for k in ("__ST", "_P_T", "_PS_", "_PST"):
            txt = re.sub(r"/\*.*?\*/", "", (Path(resid) / f"wave{model}{k}.cc").read_text())
            v = [int(x, 16) for x in re.findall(r"0x([0-9a-fA-F]{2})", txt.split("{", 1)[1])]
            assert len(v) == 4096, (model, k, len(v))
            L.append("        {")
            L += ["    " + r for r in rows(v, 24)]
            L.append("        },")
        L.append("    },")
    L.append("};")
    L.append("")
    w0max = int(2 * math.pi * W0_CAP_HZ * 1.048576)
    L.append("static const uint16_t SID_W0[2][2048] = {")
    for pts in (F0_6581, F0_8580):
        f = f0_curve(pts)
        L.append("    {")
        L += ["    " + r for r in rows([min(int(2 * math.pi * x * 1.048576), w0max) >> 1 for x in f], 16)]
        L.append("    },")
    L.append("};")
    L.append("")
    L.append("static const uint16_t SID_Q1024[16] = {")
    L += rows([int(1024.0 / (0.707 + 1.0 * r / 15)) for r in range(16)], 16)
    L.append("};")
    Path(out).write_text("\n".join(L) + "\n")
    print(f"{out}: {len(L)} lines, w0 cap {w0max}")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2] if len(sys.argv) > 2 else "firmware/src/sid_tab.h")
