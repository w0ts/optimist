"""The PROPHET engine's float tables (firmware/src/engines/prophet/p5_tables.h, committed: the build does not run this).
After Melodee's tools/gen_tables.py (Kerem Kilic, GPL-3.0-only), the same formulas at our rate (44.1 kHz, no oversampling):
  P5_TPT_G[128]   the trapezoidal one-pole's g / (1 + g), g = tan(pi fc / FS), fc on our CUTOFF_HZ scale (30 Hz .. 16 kHz)
  P5_TANH[1025]   tanh(i / 128): the soft clip, linearly interpolated (|x| < 8)
  P5_EXP2[514]    2^(i / 512): one octave of the pitch ratio, interpolated
  tools/gen_p5_tables.py [OUT]"""
import math
import sys
from pathlib import Path

FS = 44100
OUT = Path(__file__).resolve().parent.parent / "firmware" / "src" / "engines" / "prophet" / "p5_tables.h"


def arr(name: str, values: list, per_line: int = 6) -> list:
    lines = [f"static const float {name}[{len(values)}] = {{"]
    for i in range(0, len(values), per_line):
        lines.append("    " + ", ".join(f"{v:.9e}f" for v in values[i:i + per_line]) + ",")
    lines.append("};")
    return lines


def main(out: Path) -> None:
    fc = [30.0 * ((16000 / 30) ** (v / 127)) for v in range(128)]
    tpt = [math.tan(math.pi * f / FS) / (1 + math.tan(math.pi * f / FS)) for f in fc]
    lines = ["/* SPDX-License-Identifier: GPL-3.0-only */",
             "/* generated by tools/gen_p5_tables.py (after Melodee's tools/gen_tables.py): do not edit */",
             "#pragma once"]
    lines += arr("P5_TPT_G", tpt)
    lines += arr("P5_TANH", [math.tanh(i / 128) for i in range(1025)])
    lines += arr("P5_EXP2", [2 ** (i / 512) for i in range(514)])
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n")
    print(f"p5 tables: {out}")


if __name__ == "__main__":
    main(Path(sys.argv[1]) if len(sys.argv) > 1 else OUT)
