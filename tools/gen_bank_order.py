"""The alphabetical order of the engines and the factory presets, fixed at build time (run by tools/build.py).

  gen_bank_order.py OUT.h

Only the order the lists SHOW changes; every stored identifier (engine UID, slot, a preset's index in its engine,
a BANK entry's name) is untouched. Two inputs:
  - firmware/src/core/registry.h ENGINE_LIST: the engines' names (as the UI shows them: VOICE, WHEEL ...);
  - firmware/src/core/bank_src.h: the factory presets, B(ENGINE, kind, uid, "NAME") entries as they were written.
Output (build/gen/felucca_bank.h, included inside model.c's BANK[] initializer), once per ENGINE_LIST variant
(FELUCCA_ANALOG2, or the measurement-only one):
  - #define ENG_ALPHA_UIDS: every engine's UID by name; model.c keeps the ones this build has;
  - the BANK entries (only with BANK_ENTRIES defined) by engine (that order), then by preset name. Each keeps its own #if guard, so a build that
    leaves an engine or a feature out has the order of the rest (a filtered sorted list stays sorted).
Sort key: case-insensitive, leading punctuation skipped, digit runs by value ("808 BOOM" before "8580 ACID").
tests/engine_order_test.py checks this file against both inputs.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REGISTRY = ROOT / "firmware/src/core/registry.h"
BANK_SRC = ROOT / "firmware/src/core/bank_src.h"

X_RE = re.compile(r'X\((\d+),\s*(\w+),\s*(\d+),\s*"([^"]*)"\)')
B_RE = re.compile(r'\bB\((\w+),\s*(\w+),\s*([\w ]+?),\s*"([^"]*)"\)')


def sort_key(name):
    """case-insensitive, leading punctuation skipped, digit runs compared by value"""
    s = re.sub(r"^[^0-9A-Za-z]+", "", name).lower()
    return [(0, int(p), "") if p.isdigit() else (1, 0, p) for p in re.findall(r"\d+|\D+", s)]


def engine_lists(text):
    """{variant: [(uid, NAME, shown name)]}: ENGINE_LIST of the ANALOG 2 build and of the measurement-only one"""
    m = re.search(r"#if FELUCCA_ANALOG2\s*\n#define ENGINE_LIST\(X\)(.*?)\n#define ENG_UID_N.*?\n#else[^\n]*\n"
                  r"#define FELUCCA_ENG_SUPER 1\n#define ENGINE_LIST\(X\)(.*?)\n#define ENG_UID_N", text, re.S)
    if not m:
        raise SystemExit("gen_bank_order: registry.h ENGINE_LIST not found")
    ex = re.search(r'#define ENGINE_LIST_EX\(X\) X\((\d+), (\w+), (\d+), "([^"]*)"\)', text)
    new = [(int(u), n, s) for u, n, _f, s in X_RE.findall(m.group(1))]
    if ex:
        new.append((int(ex.group(1)), ex.group(2), ex.group(4)))
    old = [(int(u), n, s) for u, n, _f, s in X_RE.findall(m.group(2))]
    return {"A2": new, "OLD": old}


def bank_entries(text):
    """[(guard, ENGINE, kind, uid, name)] in source order"""
    out, guards = [], []
    for line in text.splitlines():
        s = line.strip()
        if s.startswith("#if"):
            guards.append(s[3:].split("/*")[0].strip())
        elif s.startswith("#endif"):
            guards.pop()
        elif s.startswith("#"):
            raise SystemExit(f"gen_bank_order: bank_src.h: unsupported directive {s!r}")
        for e, k, u, n in B_RE.findall(line):
            out.append((" && ".join(guards), e, k, u.strip(), n))
    if text.count("B(") != len(out):
        raise SystemExit('gen_bank_order: bank_src.h: an entry that is not B(ENGINE, kind, uid, "NAME")')
    return out


def variant(engines, entries, super_is_analog):
    """(the engines' UIDs by name, the BANK lines of that variant)"""
    by_name = sorted(engines, key=lambda e: sort_key(e[2]))
    rank = {n: i for i, (_u, n, _s) in enumerate(by_name)}

    def engine_of(e):
        return "ANALOG" if super_is_analog and e == "SUPER" else e
    if super_is_analog:                        # (the ANALOG 2 build names every engine the bank does)
        missing = {e for _g, e, *_ in entries if engine_of(e) not in rank}
        if missing:
            raise SystemExit(f"gen_bank_order: bank_src.h names an engine that ENGINE_LIST lacks: {sorted(missing)}")
    # (the measurement-only list has 12 engines: the others' entries are not built there, they go last)
    ordered = sorted(entries, key=lambda x: (rank.get(engine_of(x[1]), len(rank)), sort_key(x[4])))
    body, cur = [], ""
    for g, e, k, u, n in ordered:
        if g != cur:
            if cur:
                body.append("#endif")
            if g:
                body.append(f"#if {g}")
            cur = g
        body.append(f'B({e}, {k}, {u}, "{n}")')
    if cur:
        body.append("#endif")
    return [u for u, _n, _s in by_name], body


def render(registry_text, bank_text):
    engines, entries = engine_lists(registry_text), bank_entries(bank_text)
    out = ["/* generated by tools/gen_bank_order.py from core/registry.h and core/bank_src.h: do not edit */"]
    for i, (key, sup) in enumerate((("A2", True), ("OLD", False))):
        uids, body = variant(engines[key], entries, sup)
        out += ["#if FELUCCA_ANALOG2" if i == 0 else "#else", "#define ENG_ALPHA_UIDS " + ", ".join(map(str, uids)), "#ifdef BANK_ENTRIES"] + body + ["#endif"]
    return "\n".join(out + ["#endif"]) + "\n"


def main():
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    Path(sys.argv[1]).write_text(render(REGISTRY.read_text(), BANK_SRC.read_text()))


if __name__ == "__main__":
    main()
