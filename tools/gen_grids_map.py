"""The Grids drum map for the GRIDS note generator (firmware/src/seq/gen.c; FELUCCA_NOTEGEN).

Grids keeps 25 nodes on a 5 x 5 map, each three parts (BD, SD, HH) of 32 levels (0..255): one bar of 32nd notes.
The sequencer's steps are 16ths, so only the even 32nds are kept (the odd ones are 0 in all but 49 of the 2400
cells: ghost 32nds a 16th grid cannot play), and the nodes are stored in the map's order (drum_map[x][y]), not
by their numbers: 5 x 5 x 3 x 16 = 1200 bytes.

  tools/gen_grids_map.py path/to/eurorack/grids/resources.cc > firmware/src/seq/grids_map.h
"""
import re
import sys

# grids/pattern_generator.cc drum_map[5][5] (x, then y)
DRUM_MAP = ((10, 8, 0, 9, 11), (15, 7, 13, 12, 6), (18, 14, 4, 5, 3), (23, 16, 21, 1, 2), (24, 19, 17, 20, 22))
PARTS, STEPS = 3, 32


def nodes_of(src):
    nodes = {}
    for m in re.finditer(r"node_(\d+)\[\]\s*PROGMEM\s*=\s*\{([^}]*)\}", src):
        vals = [int(v) for v in m.group(2).replace(",", " ").split()]
        if len(vals) != PARTS * STEPS or not all(0 <= v <= 255 for v in vals):
            sys.exit(f"node_{m.group(1)}: {len(vals)} values, expected {PARTS * STEPS} bytes")
        nodes[int(m.group(1))] = vals
    if sorted(nodes) != list(range(25)):
        sys.exit(f"nodes found: {sorted(nodes)}, expected node_0 .. node_24")
    return nodes


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    with open(sys.argv[1], encoding="utf-8") as f:
        nodes = nodes_of(f.read())
    out = ["/* SPDX-License-Identifier: GPL-3.0-only",
           " * Copyright 2011 Emilie Gillet (Mutable Instruments Grids: pichenettes/eurorack grids/resources.cc,",
           " * GPL-3.0-or-later). Generated by tools/gen_grids_map.py: do not edit. */",
           "/* GRIDS_MAP[x][y][part][step]: the drum map's node at (x, y) (pattern_generator.cc drum_map), part BD SD HH,",
           " * the level (0..255) of each 16th of the bar (Grids' even 32nds) */",
           "static const uint8_t GRIDS_MAP[5][5][3][16] = {"]
    for x in range(5):
        out.append("    {")
        for y in range(5):
            n = nodes[DRUM_MAP[x][y]]
            rows = []
            for p in range(PARTS):
                row = n[p * STEPS:(p + 1) * STEPS:2]
                rows.append("{" + ", ".join(str(v) for v in row) + "}")
            out.append(f"        {{{', '.join(rows)}}},   /* node {DRUM_MAP[x][y]} */")
        out.append("    },")
    out.append("};")
    print("\n".join(out))


if __name__ == "__main__":
    main()
