# fm-106's DSP tables (data only) as firmware/src/engines/juno/juno_tables.h, renamed JUNO_* (the JUNO engine).
# fm-106 by PatttF, github.com/PatttF/fm-106 at be74757 (GPL-3.0-only); its fm106_tables.h is the input:
#   python3 -I tools/gen_juno_tables.py FM106/firmware/src/fm106_tables.h firmware/src/engines/juno/juno_tables.h
# The smooth tables whose steps fit a byte are packed without loss (juno_dsp.h juno_dtab): every 16th value
# (JUNO_x_A, uint16) and every step less the table's smallest one (JUNO_x_D, uint8; JUNO_x_B the smallest step).
# FB_SCALE without its flat ends (JUNO_FB_SCALE_T from JUNO_FB_SCALE_LO, the values below and above it its ends);
# INV_FB_SCALE is round(2^24 / FB_SCALE) but at one point (JUNO_INV_FB_FIX: one less there), juno_res_at.
# The script decodes each packed table and stops if a value differs from fm-106's.
import re, sys

WANT = ["VCF_G1", "RES_K", "FB_SCALE", "INV_FB_SCALE", "PEAK_PULL", "OTA_SAT", "SUB_LEVEL_J106",
        "NOISE_LEVEL_J106", "VCA_HW"]
PACKED = {"VCF_G1Q", "RES_K", "PEAK_PULL", "VCA_HW"}
src = open(sys.argv[1]).read()
out = ["/* SPDX-License-Identifier: GPL-3.0-only */",
       "/* The JUNO engine's tables (eng_juno.c): fm-106 by PatttF (https://github.com/PatttF/fm-106 at be74757,",
       " * fm106_tables.h, GPL-3.0-only), made by its gen_fm106_data.py from Ultramaster KR-106 by Kayrock Screenprinting",
       " * (https://github.com/kayrockscreenprinting/ultramaster_kr106, GPL-3.0): J106DACHzTable.h kV4Hz (one Juno-106",
       " * voice card's cutoff measured at 93 DAC codes, interpolated), KR106VCF_OPTIMIZED.h, KR106VCA.h kVCATableHW (a",
       " * circuit equation solved), KR106Voice.h (the sub and noise levels measured). No envelope (ROM) table. Generated by",
       " * gen_juno_tables.py: the values unchanged (the names FM106_x -> JUNO_x); the cutoff table VCF_G1 kept at every",
       " * 4th of its 4096 points and its last (VCF_G1Q, juno_dsp.h juno_coef), the OTA's at every 2nd (OTA_SAT2,",
       " * juno_ota_sat); the tables in _A / _D / _B packed without loss: every 16th value and each step less the",
       " * smallest (juno_dsp.h juno_dtab); FB_SCALE without its flat ends (FB_SCALE_T), INV_FB_SCALE computed from it",
       " * (juno_res_at). */", ""]


def emit(typ, name, vals):
    coded = name == "VCF_G1Q_D"              # (tools/gen_tables.py reads it from the header and codes it, TAB_CODED_ALL)
    if coded:
        out.append("#if !TAB_JUNO_VCF_G1Q_D_CODED   /* (the target with TAB_CODED_ALL: delta-coded in the boot stream, expanded into the pool at")
        out.append("                                 * boot, felucca_tables.h gen_tables.py carr: the same values, not this copy) */")
    out.append("static const %s JUNO_%s[%d] = {" % (typ, name, len(vals)))
    for i in range(0, len(vals), 16):
        out.append("    " + ", ".join(str(v) for v in vals[i:i + 16]) + ",")
    out.append("};")
    if coded:
        out.append("#endif")


def unpack(a, d, b, i):                      # (juno_dsp.h juno_dtab)
    s = a[i >> 4] + b * (i & 15)
    for k in range((i & ~15) + 1, i + 1):
        s += d[k]
    return s


for name in WANT:
    m = re.search(r"static const (u?int16_t) FM106_%s\[(\d+)\] = \{(.*?)\};" % name, src, re.S)
    if not m:
        sys.exit("missing " + name)
    typ, n, body = m.group(1), int(m.group(2)), m.group(3)
    vals = [int(x) for x in re.findall(r"-?\d+", body)]
    if len(vals) != n:
        sys.exit("%s: %d values, %d declared" % (name, len(vals), n))
    if name == "VCF_G1":                     # every 4th point and the last: juno_coef interpolates between them
        vals, n, name = vals[::4] + [vals[-1]], 1025, "VCF_G1Q"
    if name == "OTA_SAT":                    # every 2nd of its 257 (a smooth Pade curve): juno_ota_sat interpolates
        vals, n, name = vals[::2], 129, "OTA_SAT2"
    if name == "FB_SCALE":
        fb = vals
        lo = max(i for i in range(n) if vals[i] == vals[0])
        hi = min(i for i in range(n) if vals[i] == vals[-1])
        seg = vals[lo:hi + 1]
        if any(seg[min(max(i - lo, 0), len(seg) - 1)] != vals[i] for i in range(n)):
            sys.exit("FB_SCALE: the trimmed table decodes differently")
        out.append("#define JUNO_FB_SCALE_LO %d" % lo)
        emit(typ, "FB_SCALE_T", seg)
        continue
    if name == "INV_FB_SCALE":
        bad = [i for i in range(n) if (16777216 + fb[i] // 2) // fb[i] != vals[i]]
        if len(bad) != 1 or (16777216 + fb[bad[0]] // 2) // fb[bad[0]] - 1 != vals[bad[0]]:
            sys.exit("INV_FB_SCALE: not 2^24 / FB_SCALE but at one point, one less (%s)" % bad)
        out.append("#define JUNO_INV_FB_FIX %d" % bad[0])
        continue
    if name not in PACKED:
        emit(typ, name, vals)
        continue
    steps = [0] + [b - a for a, b in zip(vals, vals[1:])]
    bias = min(steps[1:])
    d = [0] + [s - bias for s in steps[1:]]
    a = vals[::16]
    if max(d) > 255 or min(a) < 0 or max(a) > 65535:
        sys.exit("%s: does not pack (steps %d..%d)" % (name, bias, bias + max(d)))
    if any(unpack(a, d, bias, i) != vals[i] for i in range(n)):
        sys.exit(name + ": the packed table decodes differently")
    out.append("#define JUNO_%s_B %d" % (name, bias))
    emit("uint16_t", name + "_A", a)
    emit("uint8_t", name + "_D", d)
open(sys.argv[2], "w").write("\n".join(out) + "\n")
