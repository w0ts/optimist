"""The PLAITS engine's tables: firmware/src/engines/plaits/plaits_tables.h (committed; run again only to change them).

  python3 -I tools/gen_plaits_tables.py firmware/src/engines/plaits/plaits_tables.h

PL_WS[5][257]  the waveshapers inverse tan, inverse sin, linear, bump, double bump (Plaits' ws_* i16 tables, the same
               257 points, Q15), WAVSH's HARMONICS morphs through them
PL_FOLD[257]   the bipolar wavefolder (Plaits' lut_fold) and PL_FOLD2[257] the Serge-like folder (lut_fold_2), Q15, at
               every second point of Plaits' 516 (linear interpolation in the engine, Hermite in Plaits'), read at
               index t in 0..1 as Plaits' InterpolateHermite(lut_fold + 1, t, 512) is: x = 2 t - 1 + 1/256
Pure Python (no numpy): the same formulas."""
import math
import sys
from pathlib import Path

WS = 128   # WAVESHAPER_SIZE (the shapers)
FOLD = 512  # WAVESHAPER_SIZE (the folders)


def flip(v):
    """Plaits' flip: the odd mirror of v[0..WS] around its first point, 2 WS + 1 values, Q15"""
    full = [-x for x in v[WS:0:-1]] + list(v)
    return [int(round(x * 32767.0)) for x in full]


def shapers():
    x = [i / WS for i in range(WS + 1)]
    tan = [math.atan(8 * math.cos(math.pi * a)) for a in x]
    scale = max(tan)
    fade = [min(1.0, 4.0 - 4.0 * a) for a in x]
    bump = [(1.0 - math.cos(math.pi * a * 1.5)) * (1.0 - math.cos(math.pi * f)) / 4.5 for a, f in zip(x, fade)]
    double_bump = [math.sin(math.pi * a * 1.5) for a in x]
    inverse_sin = [math.acos(1 - 2 * a) / math.pi for a in x]
    inverse_tan = [math.acos(math.tan(scale * (1.0 - 2.0 * a)) / 8.0) / math.pi for a in x]
    return [flip(inverse_tan), flip(inverse_sin), flip(x), flip(bump), flip(double_bump)]


def deadband(v_in, r_in, r_load, r_fb=150.0e3, v_sat=10.47):
    v_out = min(max(-r_fb / r_in * v_in, -v_sat), v_sat)
    return (v_in * r_fb * r_load + v_out * r_in * r_load) / (r_fb * r_load + r_in * r_load + r_in * r_fb)


def diode(x):
    return 0.7 * x / (0.3 + abs(x))


def folders():
    """Plaits' two folders on its own grid (516 points, the last repeated), normalized there; then read at our 257"""
    xs = [i / (FOLD / 2.0) - 1.0 for i in range(FOLD + 4)]
    xs[-1] = xs[-2]

    def bipolar(x):
        window = math.exp(-x * x * 4) ** 2
        return math.sin(8 * math.pi * x) * window + math.atan(3 * x) * (1 - window)

    def serge(x):
        v_in = x * 12.0
        s1 = deadband(v_in, 10e3, 100e3)
        s2 = deadband(v_in, 49.9e3, 44.2e3)
        s3 = deadband(v_in, 91e3, 18e3)
        s4 = deadband(v_in, 30e3, 71.4e3)
        s5 = deadband(v_in, 68e3, 33.0e3)
        s45 = -33.0 / 71.4 * s4 - 33.0 / 33.0 * s5 - 33.0 / 240.0 * v_in
        return diode(-150.0 / 100.0 * s1 - 150.0 / 44.2 * s2 - 150.0 / 18.0 * s3 - 150.0 / 33.0 * s45)

    nb = max(abs(bipolar(x)) for x in xs)
    ns = max(serge(x) for x in xs)
    pts = [j / 128.0 - 1.0 + 1.0 / 256.0 for j in range(257)]
    return ([int(round(32767 * bipolar(x) / nb)) for x in pts],
            [int(round(32767 * max(-1.0, min(1.0, serge(x) / ns)))) for x in pts])


def arr(vals: list, per: int = 16) -> list:
    out = []
    for i in range(0, len(vals), per):
        out.append("    " + ", ".join(str(v) for v in vals[i:i + per]) + ",")
    return out


def main():
    dst = Path(sys.argv[1] if len(sys.argv) > 1 else "firmware/src/engines/plaits/plaits_tables.h")
    ws = shapers()
    fold, fold2 = folders()
    L = ["/* SPDX-License-Identifier: MIT",
         " * Copyright 2016 Emilie Gillet (emilie.o.gillet@gmail.com): the curves (Mutable Instruments Plaits,",
         " * plaits/resources/lookup_tables.py). Generated by tools/gen_plaits_tables.py: do not edit. */",
         "/* The PLAITS engine's tables (eng_plaits.c), Q15: the five waveshapers (Plaits' ws_* tables, 257 points),",
         " * the two wavefolders at every second point of Plaits' 516 (PL_FOLD lut_fold, PL_FOLD2 lut_fold_2) */",
         "/* (TAB_PL_WS_CODED: the target with TAB_CODED_ALL has PL_WS delta-coded in the boot stream and expanded into",
         " * the pool at boot, felucca_tables.h gen_tables.py carr: the same values, not this copy) */",
         "#if !TAB_PL_WS_CODED",
         "static const int16_t PL_WS[5][257] = {"]
    for t in ws:
        L.append("  {")
        L += arr(t)
        L.append("  },")
    L += ["};", "#endif"]
    L.append("static const int16_t PL_FOLD[257] = {")
    L += arr(fold)
    L.append("};")
    L.append("static const int16_t PL_FOLD2[257] = {")
    L += arr(fold2)
    L.append("};")
    dst.write_text("\n".join(L) + "\n")
    print(f"plaits tables: {dst}")


if __name__ == "__main__":
    main()
