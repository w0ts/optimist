"""The capture image's constants from the user's own copy of the AC79 SDK's apps/common/net/wifi_conf.c (Apache-2.0),
as a default build of it has them: the RX detection thresholds and wl_rfd_ram_lut of the active branch of its
`#if 0 ... #else ... #endif` (the "stronger against interference" one), and the switches the RF code reads. The output
is a local, git-ignored file (tools/wifi_capture/README.md); nothing of the SDK is committed.

  tools/wifi_capture/gen_conf.py <wifi_conf.c> <out.c>
"""
import re
import sys

SWITCHES = {                     # the values a default build takes (no RF test, no SDIO slave, no external PA)
    "WIFI_PA_ENABLE": ("const char", 0),
    "WL_TX_DEBUG": ("const char", 0),
    "WL_RX_DEBUG": ("const char", 0),
    "wifi_temperature_drift_trim_on": ("const char", 0),   # (off here: its timer never runs in the capture)
    "RFIinitUseTrimValue": ("const unsigned char", 1),
    "CONFIG_SDIO_SLAVE_MODE": ("const unsigned char", 0),
    "WIFI_TX_FULL_WAIT_MODE": ("const unsigned char", 1),
    "config_asser": ("const int", 1),
    "MAX_REORDERING_MPDU_NUM": ("const unsigned int", 1),   # (CONFIG_NO_SDRAM_ENABLE's values: the FM-1 has no SDRAM)
    "RxReorderEnable": ("const unsigned char", 0),
    "MAX_PACKETS_IN_QUEUE": ("const unsigned short", 16),
    "MAX_LEN_OF_BSS_TABLE": ("const unsigned char", 2),
    "MAX_CHANNEL_TIME_BSS_INFRA": ("const unsigned short", 200),
    "WIFI_CHANNEL_QUALITY_INDICATION_BAD": ("const char", 5),
    "WIFI_COLD_START_FAST_CONNECTION": ("const unsigned char", 1),
    "WL_TX_ERR_RATIO_DEBUG_SEC": ("const char", 0),
    "WL_RX_ERR_RATIO_DEBUG_SEC": ("const char", 0),
    "WL_RX_BACK_GROUND_ERR_CNT_PER_SECOND": ("const unsigned short", 10),
    "WL_TX_PEND_DEBUG_SEC": ("const unsigned char", 2),
    "WL_RX_PEND_DEBUG_SEC": ("const char", 2),
    "WL_RX_OVERFLOW_DEBUG": ("const char", 0),
}
THRESHOLDS = ("STF_END_CNT_THR_VAL", "STF_DET_CNT_THR_VAL", "DS_DET_CNT_THR0_VAL", "STF_DET_THR1_VAL", "STF_DET_THR2_VAL",
              "STF_DET_THR3_VAL", "DSSS_XCDET_THR1_VAL", "DSSS_XCDET_THR2_VAL", "DS_VLD_CNT_THR_VAL", "DS_DET_CNT_THR1_VAL")


def active_branch(src: str) -> str:
    """the #else part of the '#if 0  //WIFI RX' block"""
    start = src.index("#if 0  //WIFI RX")
    els = src.index("#else", start)
    end = src.index("#endif", els)
    return src[els:end]


def main() -> int:
    src = open(sys.argv[1], encoding="utf-8", errors="replace").read()
    part = active_branch(src)
    out = ["/* generated by tools/wifi_capture/gen_conf.py from the user's wifi_conf.c: local only, never committed */"]
    for name, (ctype, value) in SWITCHES.items():
        out.append(f"{ctype} {name} = {value};")
    for name in THRESHOLDS:
        m = re.search(rf"const u32 {name}\s*=\s*(\d+)\s*;", part)
        if not m:
            raise SystemExit(f"gen_conf: {name} not found in the active branch")
        out.append(f"const unsigned int {name} = {m.group(1)};")
    m = re.search(r"const unsigned long wl_rfd_ram_lut\s*\[256\]\[2\]\s*=\s*\{(.*?)\};", part, re.S)
    if not m:
        raise SystemExit("gen_conf: wl_rfd_ram_lut not found in the active branch")
    words = re.findall(r"0x[0-9A-Fa-f]+|\b\d+\b", re.sub(r"//[^\n]*|/\*.*?\*/", "", m.group(1), flags=re.S))
    if len(words) != 512:
        raise SystemExit(f"gen_conf: wl_rfd_ram_lut has {len(words)} words, not 512")
    rows = [f"    {{{words[i]}, {words[i + 1]}}}," for i in range(0, 512, 2)]
    out.append("const unsigned long wl_rfd_ram_lut[256][2] = {")
    out.extend(rows)
    out.append("};")
    # the STA profile (Ralink's .dat text the driver parses), verbatim, with power save off (PSMode=CAM: Link needs it)
    i = src.index("static const char WL_STA_DAT[] = {")
    j = src.index("\n};", i) + 3
    out.append("#define WL_STA_SLEEP 0")
    out.append(src[i:j])
    out.append("const char *GET_WL_STA_DAT(void) { return WL_STA_DAT; }")
    open(sys.argv[2], "w").write("\n".join(out) + "\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
