def lfo_delta():
    """lfo.cc Lfo::reset: delta_ = lfoSource[rate] * lforatio_ (uint32 lforatio_, then double product)"""
    lforatio = int(4437500000.0 * N / FS) & 0xFFFFFFFF
    return [int(x * lforatio) & 0xFFFFFFFF for x in LFO_SOURCE]


def detune_q8():
    """dx7note.cc osc_freq (Dexed): detuneRatio * logfreq per DETUNE step, Q8, per MIDI note"""
    base, step = 50857777, (1 << 24) // 12
    out = []
    for mn in range(128):
        lf = base + step * mn
        r = 0.0209 * math.exp(-0.396 * (lf / (1 << 24))) / 7
        out.append(int(math.floor(r * lf * 256 + 0.5)))
    return out


def main():
    out = sys.argv[1]
    lfo_unit = int(N * 25190424 / FS + 0.5)
    penv_unit = int(N * (1 << 24) / (21.3 * FS) + 0.5)
    log2e = 1.0 / math.log(2.0)
    am_a = int(round(12.2 * log2e * (1 << 24)))        # Dexed's amp mod: exp(sens / 262144 * 0.07 + 12.2)
    am_b = int(round(0.07 * log2e / 262144 * (1 << 24) * 65536))
    rows = [
        "/* generated by tools/gen_dx7_tables.py: msfa's tables (Apache-2.0), 44.1 kHz, 32-sample blocks */",
        "#pragma once",
        "#include <stdint.h>",
        f"#define DX7_LG_N {LG_N}",
        f"#define DX7_LFO_UNIT {lfo_unit}u",
        f"#define DX7_PENV_UNIT {penv_unit}",
        f"#define DX7_AM_A {am_a}",
        f"#define DX7_AM_B {am_b}",
    ]

    def arr(decl, vals, per=8):
        rows.append(decl + " = {")
        for i in range(0, len(vals), per):
            rows.append("    " + ", ".join(str(v) for v in vals[i:i + per]) + ",")
        rows.append("};")

    # the sine table is made at start-up from these (msfa's integer recurrence: dx7_core.c)
    dphase = 2 * math.pi / 1024
    rows.append(f"#define DX7_SIN_C {math.floor(math.cos(dphase) * (1 << 30) + 0.5)}")
    rows.append(f"#define DX7_SIN_S {math.floor(math.sin(dphase) * (1 << 30) + 0.5)}")
    ex = exp2_table()
    arr("static const uint32_t DX7_EXP2[1025]", [f"{v}u" for v in ex])
    # the frequency LUT from the exp2 table: (exp2[i] K + 2^31) >> 32, + a correction of -1 / 0 / +1 (2 bits)
    fr = freq_table()
    k = int(round(float(1 << 44) / FS / (1 << 30) * (1 << 32)))
    fix = [fr[i] - ((ex[i] * k + (1 << 31)) >> 32) for i in range(1025)]
    if min(fix) < -1 or max(fix) > 1:
        raise SystemExit("gen_dx7_tables: the frequency LUT needs more than a 2-bit correction")
    rows.append(f"#define DX7_FREQ_K {k}u")
    packed = [sum((fix[i + j] + 1) << (2 * j) for j in range(4) if i + j < 1025) for i in range(0, 1025, 4)]
    arr("static const uint8_t DX7_FREQ_FIX[257]", packed, 16)
    arr("static const uint32_t DX7_LFO_DELTA[100]", [f"{v}u" for v in lfo_delta()])
    arr("static const int32_t DX7_DETUNE_Q8[128]", detune_q8())
    arr("static const int32_t DX7_FINE_TAB[100]", [int(math.floor(24204406.323123 * math.log(1 + 0.01 * f) + 0.5))
                                              for f in range(100)])
    with open(out, "w") as f:
        f.write("\n".join(rows) + "\n")
    print(f"dx7 tables: {out}")


if __name__ == "__main__":
    main()
