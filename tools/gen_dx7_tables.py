# Tables of the DX7 engine (firmware/src/dx7_core.c), computed exactly as msfa computes them at
# start-up (Google music-synthesizer-for-android, Dexed's copy; Apache-2.0): sine, exp2, the
# frequency LUT, the LFO rates and the per-block units at 44.1 kHz with 32-sample blocks.
# Doubles here are the C doubles there, so the tables come out bit for bit the same.
#   gen_dx7_tables.py OUT.h
import math
import sys

FS = 44100.0
LG_N = 5                      # SLOOP renders 32-sample blocks (msfa: 64)
N = 1 << LG_N


def sin_table():
    """sin.cc Sin::init (SIN_LG_N_SAMPLES 10): values only, entry 1024 = 0 (the wrap); not emitted (the
    firmware makes it the same way: dx7_tables_init), kept as the reference"""
    n = 1024
    dphase = 2 * math.pi / n
    c = math.floor(math.cos(dphase) * (1 << 30) + 0.5)
    s = math.floor(math.sin(dphase) * (1 << 30) + 0.5)
    r = 1 << 29
    u, v = 1 << 30, 0
    t = [0] * (n + 1)
    for i in range(n // 2):
        t[i] = (v + 32) >> 6
        t[i + n // 2] = -((v + 32) >> 6)
        nt = (u * s + v * c + r) >> 30
        u = (u * c - v * s + r) >> 30
        v = nt
    return t


def exp2_table():
    """exp2.cc Exp2::init (EXP2_LG_N_SAMPLES 10): values only, entry 1024 = 2^31"""
    n = 1024
    inc = math.exp2(1.0 / n) if hasattr(math, "exp2") else 2.0 ** (1.0 / n)
    y = float(1 << 30)
    t = []
    for _ in range(n):
        t.append(math.floor(y + 0.5))
        y *= inc
    t.append(1 << 31)
    return t


def freq_table():
    """freqlut.cc Freqlut::init: 1025 entries"""
    y = float(1 << (24 + 20)) / FS
    inc = math.pow(2, 1.0 / 1024)
    t = []
    for _ in range(1025):
        t.append(math.floor(y + 0.5))
        y *= inc
    return t


